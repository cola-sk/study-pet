"""Generate firmware and browser rules from pets/*.json; --check checks drift."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def minute(value):
    hour, minute = map(int, value.split(':'))
    assert 0 <= hour < 24 and 0 <= minute < 60
    return hour * 60 + minute


def generate():
    profiles = [json.loads(file.read_text()) for file in sorted((ROOT / 'pets').glob('*.json'))]
    assert profiles and len({p['id'] for p in profiles}) == len(profiles)
    entries = []
    for p in profiles:
        assert p['id'].isascii() and p['id'].replace('_', '').isalnum() and len(p['id']) < 24
        assert -720 <= p['timezone_offset_minutes'] <= 840
        assert 1 <= len(p['meals']) <= 4 and 1 <= len(p['sleep_windows']) <= 6
        fields = [f'    .id = {json.dumps(p["id"])}, .name = {json.dumps(p["name"])},',
                  f'    .timezone_offset_minutes = {p["timezone_offset_minutes"]},',
                  f'    .meals = {{{", ".join(str(minute(m)) for m in p["meals"])}}}, .meal_count = {len(p["meals"])},']
        for key in ['minimum_meal_gap', 'unsynced_hunger', 'water_interval', 'companionship_interval', 'sleepy_lead', 'manual_nap', 'wake_grace']:
            value = p[key + '_minutes']
            assert isinstance(value, int) and 0 < value <= 1440
            fields.append(f'    .{key}_s = {value * 60},')
        windows = [(minute(a), minute(b)) for a, b in p['sleep_windows']]
        assert all(a != b for a, b in windows)
        occupied = set()
        for a, b in windows:
            minutes = set(range(a, b)) if a < b else set(range(a, 1440)) | set(range(b))
            assert not occupied & minutes, 'Sleep windows overlap'
            occupied |= minutes
        fields.append('    .sleep_windows = {' + ', '.join('{' + f'{a}, {b}' + '}' for a, b in windows) + '},')
        fields.append(f'    .sleep_window_count = {len(windows)},')
        entries.append('{\n' + '\n'.join(fields) + '\n}')
    assert any(p['id'] == 'husky' for p in profiles)
    c = '// Generated by tools/generate_pet_profiles.py. Edit pets/*.json.\n#include "pet_model.h"\n#include <string.h>\n\n'
    c += 'static const pet_profile_t profiles[] = {\n' + ',\n'.join(entries) + '\n};\n'
    c += 'const pet_profile_t *pet_profile_find(const char *id) {\n    if (!id) return NULL;\n    for (unsigned i = 0; i < sizeof(profiles) / sizeof(profiles[0]); i++)\n        if (!strcmp(profiles[i].id, id)) return &profiles[i];\n    return NULL;\n}\n'
    c += 'const pet_profile_t *pet_profile_default(void) { return pet_profile_find("husky"); }\n'
    js = '// Generated by tools/generate_pet_profiles.py. Edit pets/*.json.\nwindow.petProfiles = ' + json.dumps({p['id']: p for p in profiles}, ensure_ascii=False, indent=2) + ';\n'
    return {ROOT / 'main/pet_profiles.c': c, ROOT / 'preview/pet-profiles.js': js}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for file, value in generate().items():
        if args.check:
            assert file.exists() and file.read_text() == value, f'{file} needs regeneration'
        else:
            file.write_text(value)
